-- 作品下线时，给当时处于公开状态的版本打上「已撤回」标记。
--
-- 背景：`published` 是作品版本的终态（`WORK_TRANSITIONS`）。下线不能把状态改回
-- `private`——那等于抹掉「当初审核通过了」这段历史，派生过它的作品来源也会漂移。
-- 所以关闭公共访问的做法是：容器清 `published_version_id`，版本上留一条撤回记录。
--
-- 为什么不能只靠容器指针：先发布 v1 → 下线 → 再发布 v2，指针重新非空，而 v1
-- 仍然是 `published`。只判「指针非空」会让 v1 及其产物重新对外开放，绕过了
-- 「重新公开需新版本审核」。撤回必须持久化在版本上，才能一直生效。
--
-- 幂等：只加一列，存量数据为 NULL（= 从未被撤回），是否公开仍由 status 与容器
-- 指针共同决定。

ALTER TABLE work_versions ADD COLUMN public_revoked_at TEXT;
